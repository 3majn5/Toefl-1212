    /** Builds a cloze item from a full sentence, obscuring [word] the same way as the generated items. */
    private fun cloze(id: String, title: String, sentence: String, word: String, hint: String, explanation: String): CompleteWordsExercise {
        val obscured = Toefl2026PracticeData.obscureWordForToefl2026(word)
        val text = sentence.replaceFirst(Regex("(?<![A-Za-z])${Regex.escape(word)}(?![A-Za-z])", RegexOption.IGNORE_CASE), obscured)
        return CompleteWordsExercise(id, title, text, word, obscured, hint, explanation)
    }

